/// 上一次取到的下标 —— 只存内存（每次冷启动归零），不持久化。
int? _lastIndex;

/// 随机取一条名句：[Random] 无种子；连续两次不会拿到同一条（多于一条
/// 时在剩余里重摇）。调用方（主页）每次进页取一次即可。
Quote nextQuote([Random? random]) {
  final rng = random ?? Random();
  if (kQuotes.length < 2) return kQuotes.first;
  var i = rng.nextInt(kQuotes.length);
  while (i == _lastIndex) {
    i = rng.nextInt(kQuotes.length);
  }
  _lastIndex = i;
  return kQuotes[i];
}
